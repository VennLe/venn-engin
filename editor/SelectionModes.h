#pragma once
// ============================================================
// editor/SelectionModes —— 视口里"怎么选"（Tab 径向菜单切换）
//
// ------------------------------------------------------------
// 它和 EditMode 的分工
// ------------------------------------------------------------
//   EditMode      决定"整套编辑工具"（地形 / 植被 / 建模 / 动画…），
//                 是左栏 Modes 列表里那 9 行（Select 不再是其中一项）。
//   SelectionMode 只在**没有专属工具**的常态下起作用：鼠标左键在视口里
//                 画的是一点点、一个矩形、一条套索还是一把刷子。
//
// 2026-11-04 用户要求把"选择"从模式类型列表里摘掉，改由**按住 Tab 的
// 径向菜单**来换 —— 理由很直接：它与别的模式不是同一层的东西。地形 /
// 植被 / 建模是"换一整套工具"，而"点选 / 框选 / 套索 / 刷选"是同一套
// 工具里的四个手感。混在一个单选列表里，用户每换一次手感就要"离开
// 选择模式再回来"，而且列表里永远有一行是被工具条 Q 键重复表达的。
//
// ------------------------------------------------------------
// 为什么四个而不是更多
// ------------------------------------------------------------
// 径向菜单的扇区宽度 = 360° / n。四块 = 每块 90°，鼠标甩到哪个方向都
// 不会误判；八块就要求用户精确定向，反而比列表慢。UE / Blender / Maya
// 的同类菜单也都在 4~8 之间取少的那一端。
// ============================================================

#include "ecs/World.h"

#include <imgui.h>

namespace editor {

enum class SelectionMode : int {
    Pick = 0,    // 普通选择：左键点谁选谁，点空白清空
    Box = 1,     // 框选：拖一个矩形，碰到就选
    Lasso = 2,   // 套索：手绘一条闭合曲线，圈住的选
    Brush = 3,   // 刷选：按住左键涂，刷过的选
};

constexpr int kSelectionModeCount = 4;

// 英文名（TR() 的键，也是左栏面板与径向菜单上显示的字）
//
// ⚠ 径向菜单里会把它**缩小到 0.82 倍**再画：扇区的水平可用宽度约 106px，
//   而 "Lasso Select" 在默认字号下量出来 ~110px（实测四个标签会互相压边）。
//   不另做一套"短名"是因为 `Box` / `Brush` 在词表里已经各有所指
//   （"盒" / "笔刷"），再加短名只会让同一个词在两处意思不同。
const char* selectionModeName(SelectionMode m);
// 稳定 id（日志 / 落盘 / 自动化断言用，小写下划线）
const char* selectionModeId(SelectionMode m);
// 一句话说明（径向菜单悬浮提示 + 左栏面板的说明行）
const char* selectionModeHint(SelectionMode m);
// 夹到合法范围（环境变量 / 落盘的脏数据）
SelectionMode clampSelectionMode(int v);

// 16×16 单位网格的矢量字形，与 paintEditModeIcon 同一套画法。
void paintSelectionModeIcon(ImDrawList* dl, ImVec2 p, float s,
                            SelectionMode m, ImU32 col);

// ------------------------------------------------------------
// 一个实体能不能被"选择方式"选中 —— **四种方式共用这一条判据**
// ------------------------------------------------------------
// 2026-11-04 用户要求："所有的选择类型只能对场景中天空 / 地面 / 云层 /
// 星空之外的物体对象操作生效"。
//
// 三类**不是物体**的东西，逐条对应到代码里：
//
//   ① 天空 / 云层 / 星空 —— **根本不是实体**，它们是 `render::SkyParams`
//      驱动的全屏程序化绘制（见 scene/Scene.h 的 `m_sky`）。没有实体就没
//      句柄，`each<TransformComponent>` 扫不到，框选 / 套索 / 刷选天然碰不
//      到；点选打到那片像素时射线只命中远平面，`pick` 返回 miss。这一条
//      不需要额外代码，但需要一次**断言**证明它（verify_selection_modes 的
//      C6：在天空区域拖框 → n=0），否则"以后给天空加实体"会静默地把它
//      变成可选。
//
//   ② 地面 / 地形 —— 是实体，靠 `LockedComponent` 标成"编辑器参照物"：
//      看得见、动不了、也选不中。**注意**：模板场景里的 Ground 一度漏了
//      这个标记（`EditorScene` 新建空场景时会加，从 JSON 载入的不会），
//      于是框选会把整块地面带进选择集 —— 那正是这条需求报上来的现象。
//
//   ③ 没有 Transform 的实体 —— 纯逻辑节点（比如没挂场景的配置项）。
//      它们没有屏幕位置，任何"按屏幕选"的方式都无从判定。
//
// ⚠ 判据放在这里而不是各写一份：四个选择路径（点选走 PickingSystem、
//   框选 / 套索 / 刷选走各自的 each 循环）里任何一处单独漏掉一类，用户看到
//   的都是"这个方式能选中地面，那个不能"——那种不一致极难归因。
bool isSelectableObject(const ecs::World& w, ecs::Entity e);

} // namespace editor
