#pragma once
// ============================================================
// editor/InputMapIO —— 键位绑定表的编辑器侧落盘（G06）
//
// 为什么单独一个文件而不是塞进 EditorLayoutIO：
//   · 布局 / 偏好是**编辑器自己的**状态（用户界面长什么样）；
//   · 键位绑定是**游戏资产**（Game.exe 也读它，出货时随包走）。
//   两者的生命周期、默认路径、自动化规则都不一样，混在一起迟早会
//   因为"布局要不要禁写"顺手把游戏键位也禁了。
//
// ------------------------------------------------------------
// 与运行时的分工
// ------------------------------------------------------------
//   编辑器：Preferences ▸ Bindings 页改 → 写这里 → `assets/input_map.json`
//   运行时：`RuntimeApp::onInit` 起手读同一个文件；读不到就用
//           `core::InputMap::makeDefault()` 的出厂绑定。
//
//   **文件不存在是完全正常的状态**（第一次启动 / 从来没改过键位）。
//   出厂绑定的唯一事实源是 `makeDefault()`，这个文件只是**覆盖**。
//   刻意不在仓库里塞一份 input_map.json 当作"默认资产"：那样出厂表
//   就有两份，改了 makeDefault 忘了改 JSON 就会出现"新玩家键位不对"。
//
// ------------------------------------------------------------
// 自动化规则（与 EditorLayoutIO 同一条纪律，只有一处放宽，见下）
// ------------------------------------------------------------
//   · 读：自动化运行下**默认路径不读**（残留文件会把自动化结果改掉），
//         显式给路径**照读**（那是脚本指定的文件，不是残留状态）。
//   · 写：自动化运行下**默认路径拒写**。
//         ⚠ 与布局不同，**显式路径允许写** —— 理由：布局/偏好是用户的
//         私有状态，自动化写进去就是污染；而这里写的是"玩家改的键位"，
//         测试必须能覆盖"改完能存下来"这条链。把写路径做成不可测，
//         "存下来但读不回来"这类 bug 只能靠人开窗口发现。
//         代价是脚本自己负责把路径指到临时目录（工具里已钉死）。
// ============================================================

#include <string>

namespace core {
class InputMap;
}

namespace editor {

// 绑定表路径：`MYVK_EDITOR_INPUT_MAP` > 相对 `assets/input_map.json`
//（相对路径由 core::InputMap 的调用方按资产根解析，见实现的说明）
std::string editorInputMapPath();
// 路径是不是脚本**显式**给的（决定自动化下读/写放行的那个分支）
bool editorInputMapPathExplicit();
// 绑定表文件当前是否存在（面板上显示"出厂 / 来自文件"用）
bool editorInputMapFileExists();

// 读进 map。文件不存在 / 解析失败 / 自动化+默认路径 → 返回 false 且
// **一个字节都不改**（调用方保持出厂绑定）。
bool loadEditorInputMap(core::InputMap& map);

// 写盘。失败只打 WARN、返回 false，不抛。
bool saveEditorInputMap(const core::InputMap& map);

} // namespace editor
