using Map = std::unordered_map<std::string_view, const char*>;

const Map& zhMap() {
    static const Map m = [] {
        Map out;
        out.reserve(sizeof(kZh) / sizeof(kZh[0]) * 2);
        for (const Entry& e : kZh) out.emplace(e.en, e.zh);
        return out;
    }();
    return m;
}

int g_lang = static_cast<int>(Language::English);

