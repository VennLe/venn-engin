int languageCount() { return static_cast<int>(Language::Count); }

const char* languageName(int index) {
    switch (static_cast<Language>(index)) {
    case Language::Chinese: return "中文";
    case Language::English:
    default: return "English";
    }
}

void setLanguage(int index) {
    if (index < 0) index = 0;
    if (index >= languageCount()) index = languageCount() - 1;
    g_lang = index;
}

int language() { return g_lang; }

bool isChinese() { return g_lang == static_cast<int>(Language::Chinese); }

const char* tr(const char* english) {
    if (!english) return "";
    // 英文模式直接原样返回：这是**零风险**路径，也是回归的基准路径。
    if (g_lang != static_cast<int>(Language::Chinese)) return english;
    const Map& m = zhMap();
    const auto it = m.find(std::string_view(english));
    return it == m.end() ? english : it->second;
}

const char* trId(const char* english, const char* stableId) {
    if (!stableId) stableId = "";
    if (!english) english = "";
    // 缓存 key 必须带上语言：换语言后同一个 stableId 要拿到新译文。
    // 用 "语言 \x1f 英文" 当 key，避免中文模式下英文标题被当成英文模式的结果。
    static std::unordered_map<std::string, std::string> cache;
    std::string key;
    key.reserve(64);
    key += static_cast<char>('0' + (g_lang & 7));
    key += '\x1f';
    key += english;
    auto it = cache.find(key);
    if (it != cache.end()) return it->second.c_str();
    std::string v = tr(english);
    v += "###";
    v += stableId;
    return cache.emplace(std::move(key), std::move(v)).first->second.c_str();
}

