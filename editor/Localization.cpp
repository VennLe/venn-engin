// ============================================================
// editor/Localization.cpp —— 英 → 中映射表 + 查表
//
// 这张表是**唯一**的中文来源：调用点永远写英文，显示时才替换。
// 加译文 = 在 kZh[] 里加一行；删掉一行 = 该处回退英文。
//
// ⚠ 写译文时的三条硬规则：
//   1) **% 占位符必须与英文完全一致**（`%s` / `%zu` / `%.2f` / `%%` …）。
//      少一个、顺序换了，运行时格式化就会错位 —— 这类 bug 只在切到中文
//      时出现，最容易漏测。
//   2) **`\n` 要照抄**。译文换了行而英文没换，会让控件的行高/换行位置变。
//   3) 术语保持一致：Scene=场景、Entity=实体、Mesh=网格、Material=材质、
//      Component=组件、Collider=碰撞体、Emitter=发射器、Gizmo=手柄、
//      Snapping=吸附、Wireframe=线框、Viewport=视口、Hierarchy=层级、
//      Inspector=属性、Content=内容、Console=控制台、Preference=偏好。
// ============================================================

