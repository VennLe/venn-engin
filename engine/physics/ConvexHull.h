#pragma once
// ============================================================
// physics/ConvexHull —— 三维凸包（QuickHull）
//
// 为什么要它：碰撞体有两种结构，其中一种要求"按照物体几何结构，用当前
// 业内最优秀的算法找到一个"。这一步就是 Bullet 的 btConvexHullShape /
// PhysX 的 PxConvexMesh 背后干的事 —— 从网格顶点求凸包，得到一个包住
// 整个模型、且尽量贴紧它的凸多面体（模型凹进去的地方会被填平，这是凸体
// 碰撞的数学前提）。
//
// ------------------------------------------------------------
// 为什么是 QuickHull
// ------------------------------------------------------------
// 三维凸包的标准工业算法，期望 O(N log N)。二维那套 Graham 扫描 / 单调
// 链在三维没有直接对应；分治三维凸包实现复杂、常数还大。QuickHull 用
// "最远点 → 可见面集合 → 地平线（horizon）"的迭代，既快又容易写对 ——
// Bullet（btConvexHullComputer）、PhysX、CGAL 的默认三维凸包都是它。
//
// ------------------------------------------------------------
// 实现要点：冲突表（conflict list）
// ------------------------------------------------------------
// 每个"还在凸包外面"的点，只挂到**一个**它能看见的面上。每轮迭代只需要
// 把被删掉的那几个面上挂的点重新分配，而不是全量扫一遍"点 × 面"。
//
// 这一条不是优化而是**可行性**问题：UV 球有 1150 个顶点、凸包有 1150
// 个面、迭代也是 1150 轮。没有冲突表就是 1150 × 1150 × 1150 ≈ 15 亿次
// 距离计算，编辑器点一下"加碰撞体"要卡好几秒；有了冲突表就是几十万次。
//
// ------------------------------------------------------------
// 输出里为什么留 faces
// ------------------------------------------------------------
// 碰撞求解本身只需要**顶点集**（支撑函数就是 max dot(p, dir)），但可视化
// 要画线框、而凸包的"边"必须从面上提取（顶点两两相连会画出一团糊）。
// 所以面也一起返回。
// ============================================================

#include <glm/glm.hpp>

#include <cstdint>
#include <vector>

namespace physics {

struct ConvexHull {
    // 凸包顶点。全部是**输入点集里的点本身**（不插值、不新生成），
    // 顺序无意义。
    std::vector<glm::vec3> points;

    // 凸包三角面（索引进 points）。绕序统一为从外面看逆时针。
    struct Face {
        std::uint32_t a = 0, b = 0, c = 0;
    };
    std::vector<Face> faces;

    glm::vec3 minBound{0.0f};
    glm::vec3 maxBound{0.0f};
    glm::vec3 centroid{0.0f};

    bool empty() const { return points.size() < 4 || faces.empty(); }

    // 支撑函数：凸包上沿 dir 最远的点。dir 不必归一化。
    // 返回的是**点本身**（不是它在 dir 上的投影）。
    glm::vec3 support(const glm::vec3& dir) const;

    // 去重后的唯一边（每条边只出现一次，用于线框绘制）
    std::vector<std::pair<std::uint32_t, std::uint32_t>> edges() const;
};

// 从任意点集求凸包。
//   · 点数 < 4 → 返回空（调用方自己兜底）
//   · 点集退化成平面 / 直线（体积为 0）→ 返回空
//   · 输入里的重复点会被先行去重（否则初始四面体可能退化）
// eps 是"点是否在面外侧"的容差（米）。
ConvexHull buildConvexHull(const std::vector<glm::vec3>& points,
                           float eps = 1e-5f);

} // namespace physics
