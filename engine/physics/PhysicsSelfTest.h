#pragma once
// ============================================================
// physics/PhysicsSelfTest —— 无窗口的物理自检
//
// 为什么要有它：物理是**数值**系统，"看起来在动"完全不能说明它对。
// 一堆箱子能堆起来，可能只是因为求解器把穿透硬推回去了 —— 而重力大小、
// 积分格式、摩擦系数全错也照样"能动"。
//
// 所以这里的每一项都拿**解析解**当基准：
//   · 半隐式欧拉的自由落体有闭式解（z_n = z0 − g·dt²·n(n+1)/2），
//     对不上就说明积分格式被改动了（比如误写成显式欧拉，那会多出
//     ½g·dt² 每步的能量）；
//   · 无摩擦斜/平面滑动的减速度是 μ·g；
//   · 弹性碰撞的出射速度等于入射速度；
//   · 距离关节的长度必须守恒。
//
// 运行方式：MYVK_PHYS_TEST=1 ./Editor.exe —— **不初始化 Vulkan、不开窗口**，
// 在 main() 里直接跑完打印然后退出（见 editor/main.cpp）。这样它能在
// 任何机器上跑，也是回归里最快的一项。
//
// 输出格式（供 tools/verify_physics.py 解析）：
//   PHYS-TEST <名字> actual=<值> expected=<值> tol=<值> result=PASS|FAIL
//   PHYS-TOTAL pass=<n> fail=<m>
// ============================================================

namespace physics {

// 跑完全部自检，返回失败项数（0 = 全过）。
int runPhysicsSelfTest();

} // namespace physics
