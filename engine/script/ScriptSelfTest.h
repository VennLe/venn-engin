// ============================================================
// script/ScriptSelfTest —— 脚本内核的无窗口自检（S0）
//
// 为什么脚本需要自检：**脚本的错误几乎全都不报错**。
//   · 变量每帧归零 → 画面只是"没动"，像"脚本没生效"
//   · 熔断缺失 → 死循环每帧烧 20 万步，日志只报一次，帧时间崩了但看不见
//   · `time = t * timeScale` → 改倍速时时间倒退，只有做子弹时间才发现
//   · 两个实例共享一个 prints → 输出串台（看起来像"打印顺序乱了"）
// 这些都不能靠截屏发现，也不能靠"跑起来没崩"推断。所以全部用**可数的
// 事实**当基准断言（`n == 10` / `executed == 1` / `vars.empty()`）。
//
// 运行方式：`Game.exe --selftest script`（不开窗口、不需要 GPU）。
// 输出：`SCRIPT-T pass <名字> <细节>` / `SCRIPT-TOTAL pass= fail=`。
// ============================================================

namespace vks {

// 返回失败项数（0 = 全过）。
int runScriptSelfTest();

// S6 基准：`instances` 个实例、每个实例每帧 `stmts` 条语句的**帧时间**。
//
// 为什么单独一个入口而不是塞进 runScriptSelfTest：
//   · 它是**性能**判据，不是正确性判据 —— 混在一起会让"改了一条断言"
//     和"机器换了"这两件事在同一个红灯里分不开；
//   · 它要跑 200 个实例 × 上万条语句，比整套 A~E 组还慢一个量级，
//     放进日常自检会让人不想跑自检。
//
// 输出一行：`VKS-BENCH instances=200 stmts=20000 ms=<每帧毫秒>`。
// 预算写死在调用方（`tools/verify_script.py` 的 G7）—— 机器快慢不同，
// 引擎不该替使用者决定"多少毫秒算慢"。
int runScriptBench();

} // namespace vks
