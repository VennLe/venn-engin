#pragma once
// ============================================================
// assets/ModelOrientation —— 从骨架反推"这个模型的脸朝哪边"
//
// ------------------------------------------------------------
// 为什么需要它
// ------------------------------------------------------------
// 引擎实体的 yaw 语义是"yaw=0 → 正面朝 +X"（与 Camera 的 angleDir 同一套）。
// 而美术资产的正面朝哪**没有统一标准**：
//   · FBX（Y-up，正面 +Z）经 ufbx 的 (x,-z,y) 映射后 → 正面落在 -Y
//   · VRM/glTF（Y-up，正面 +Z）经 Blender 导入再导 FBX → 正面落在 **+Y**
// 所以装配时必须给一个"绕 Z 的补偿角"。以前这个角是**写死的 +90°**
// （`kDefaultModelYaw` / `RuntimeConfig::PlayerVisual::modelYaw`），
// 只对第一种资产成立。
//
// 2026-10-24 用户报障："角色往前走时，面部朝着相反的方向"。
// 根因就是默认角色换成了 VRM 来源的 alicia（正面 +Y），补偿角却还是 +90°：
//
//   R(+90°)·(0,+1,0) = (-1,0,0) = -X      ← 脸朝 -X
//   实体前进方向     = +X                  ← 人倒着走
//
// 差 180°，而当时的自检只比"左右跨度 > 前后跨度"（量的是臂展轴），
// 180° 错**恰好**不影响那个判据 → 静默通过。这条教训写在这里：
// **判据必须能证伪它要防的那个错**，否则等于没测。
//
// ------------------------------------------------------------
// 判据为什么用"脚 → 脚趾"
// ------------------------------------------------------------
// 人的脚趾永远朝前，而且**不受表情/贴图/服装影响**。实测三具资产：
//
//   alicia            LeftFoot(-0.041,-0.018) → LeftToe(+0.038,+0.060)  +Y
//   default_character LeftFoot(+0.085,+0.064) → LeftToe(+0.085,-0.063)  -Y
//   animate_girl      LeftFoot(+0.122,+0.364) → LeftToe(+0.125,+0.296)  -Y
//
// 与"脸的朝向"逐一对得上（alicia 的眼/脸网格中心在 +Y，长发重心在 -Y）。
// 比"用眼睛子网格"稳：子网格命名/数量因资产而异，脚趾骨则是人形骨架的
// 标配（Mixamo `LeftToeBase`、VRM `leftToes`、AutoRig `LeftToeBase`、
// UE mannequin `ball_l` 都带 toe/ball）。
// ============================================================

#include <glm/glm.hpp>

namespace assets {

struct Model;

// 由骨架的"脚→脚趾"方向反解**补偿角**（度，绕 +Z）。
//
// 语义与 `scene::ModelInstanceOptions::yawOffsetDeg` 一致：把它填进去，
// 模型的正面就会转到实体的 +X。
//
// 返回值会**吸附到 90° 的整数倍** —— 人形资产都是轴对齐摆的，脚趾略微
// 外八会让原始角是 -87.5° 这种数，照用会让角色歪 2.5°。
//
// 成功返回 true；骨架里找不到 foot/toe 对、或两脚方向不一致（夹角 > 45°）
// 返回 false，调用方应退回它自己声明的角度。
//
// `outLocalForward`（可空）回填**补偿前**的局部正面方向（单位向量，XY 平面）。
// `outRawDeg`（可空）回填未吸附的原始角，日志里两者都打出来便于事后追。
bool modelForwardYawDeg(const Model& m, float* outDeg,
                        glm::vec2* outLocalForward = nullptr,
                        float* outRawDeg = nullptr);

} // namespace assets
