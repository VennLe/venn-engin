#pragma once
// ============================================================
// scene/LookLimits —— 视角俯仰范围的**单一来源**
//
// 为什么单独抽一个头文件：第三人称的俯仰钳制写在**两个地方**，而且是两条
// 独立演化的代码路径 ——
//
//   runtime/PlayerController::update   （出包后 Game.exe 走这条）
//   editor/EditorApp::runPlayers       （编辑器里点 Play 走这条）
//
// 两边各写一个字面量，就等于"改了运行时忘了编辑器"。实际情况更糟：这两边
// 的 pitch **正负号相反**（运行时 m_pitch 是"相机俯角，正 = 往下看"，编辑器
// pc->pitch 是"视线仰角，正 = 抬头"），所以抄数值时极容易顺手抄成镜像 ——
// 用户报的"往上仰视和往下俯视的角度有些不正常"就是这类偏差的典型症状。
//
// 于是这里只定义**角度本身**（度 + 弧度各一份），正负号交给调用方按自己的
// 约定套。自检（`Game.exe --selftest player` 的 E 组）直接断言这两个常量，
// 编辑器那边则由 `tools/verify_look_limits.py` 静态比对源码引用。
//
// ------------------------------------------------------------
// 取值依据：人的颈椎能看多少
// ------------------------------------------------------------
// 颈椎后伸（抬头）约 45-60°，前屈（低头）约 45-50°，再加上胸腰段代偿，
// 人真的能"看脚下"到 ~70°、看头顶到 ~55°。上下**不对称**是刻意的：
//   · 抬头再往上，第三人称的臂会把相机甩到角色正下方，画面上只剩头顶和
//     天空，玩起来没有意义；55° 已经足够看树梢 / 天花板 / 飞过来的敌人。
//   · 低头给到 70°（UE 第三人称模板同量级），因为"看脚下有没有台阶 / 掉落"
//     是真正会被用到的动作。
//
// ⚠ 这两个值只讲"人怎么看"。**相机不许钻进地面**是另一件事，由
//   PlayerController 里的地面钳制负责（把相机顶到地表之上再反解俯仰），
//   不要用"缩小俯仰范围"去凑 —— 那会连带砍掉正常的仰视。
// ============================================================

namespace scene {

inline constexpr float kLookUpDeg = 55.0f;     // 抬头（视线向上）的最大角度
inline constexpr float kLookDownDeg = 70.0f;   // 低头（视线向下）的最大角度

inline constexpr float kDegToRad =
    3.14159265358979323846f / 180.0f;

inline constexpr float kLookUpRad = kLookUpDeg * kDegToRad;
inline constexpr float kLookDownRad = kLookDownDeg * kDegToRad;

} // namespace scene
