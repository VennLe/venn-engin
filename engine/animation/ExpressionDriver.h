#pragma once
// ============================================================
// animation/ExpressionDriver —— 表情的**时间驱动**（B6）
//
// `MorphComponent::weights` 是"脸此刻长什么样"，`ExpressionComponent` 是
// "这些数该怎么算"。本文件就是"算"的那一半，每帧跑一次。
//
// 它负责三件事，缺一件表情就是死的：
//
//   ① **预设 → 权重**：把一份命名表情的通道权重乘上强度写进权重表。
//      没有它，用户得每次手动推 6 根滑条才能笑一次，而且推不准。
//   ② **眨眼**：按时间自动闭合/睁开。这是"角色是不是活的"最廉价、
//      也最有效的一个信号 —— 一双永远不眨的眼睛，看两秒就出戏。
//   ③ **口型**：把语音总线的**真实音量包络**映射到张嘴幅度。
//      用正弦波或随机数假装在说话，比不做更糟：嘴型与声音**永远**不同步。
//
// ------------------------------------------------------------
// 四条语义（都是"看起来能省、省了就错"的）
// ------------------------------------------------------------
// ⚠⚠ ① **只写自己拥有的通道**，其余原样不动。理由见
//     `ecs/Components.h` 里 `ExpressionComponent` 的注释：手动滑条和
//     驱动写的是同一张权重表，驱动写满就等于"推滑条没反应"。
//
// ⚠⚠ ② **上一帧拥有、这一帧不再拥有的通道必须显式写 0**。换预设时
//     旧表情的通道要归零，否则"从笑切到怒"会把嘴角留在上扬的位置。
//
// ⚠⚠ ③ **抖动用确定性伪随机**（LCG，种子来自实体 id）。用 `rand()` 的话
//     自检无法断言"第 N 次眨眼的间隔落在 [0.85,1.15]×interval"，
//     而且两次运行结果不同 —— 那种断言只能写得很松，等于没测。
//
// ⚠⚠ ④ **包络平滑用指数（帧率无关）而不是线性逼近**。线性逼近的收敛
//     速度依赖 dt，60 fps 与 144 fps 下嘴张合的**韵律**不一样 ——
//     而韵律恰恰是口型唯一能被人眼检验的东西。
//     攻击（张嘴）快、释放（闭嘴）慢：0.02 s / 0.09 s。
//
// ------------------------------------------------------------
// 无窗口、无设备
// ------------------------------------------------------------
// 本文件只碰 `ecs::World` 与纯数值，自检里可以直接建一个 World 跑。
// ============================================================

#include "ecs/Components.h"

namespace ecs {
class World;
}

namespace anim {

// 眨眼曲线：给定"已经眨了多久"，返回闭眼程度 [0,1]。
//
//   0 ──close──► 1 ──hold──► 1 ──open──► 0
//
// `phase < 0` 或超过总时长 → 0（不眨）。三段用时都 <= 0 时也返回 0
// （退化配置不该让脸定格在闭眼）。
// 两段过渡用 smoothstep：线性闭合会让眼睑像"机械闸门"。
float blinkWeight(float phase, float close, float hold, float open);

// 一个实体本帧的驱动结果（自检与日志用；正常路径不看它）。
struct ExpressionStats {
    int driven = 0;       // 本帧真的写了权重的实体数
    int channels = 0;     // 本帧写入的通道条目总数（含归零的）
    int blinked = 0;      // 本帧**新开始**眨眼的次数
    int missing = 0;      // 预设里在本 rig 上找不到的通道数（去重后）
    float level = 0.0f;   // 本帧用的语音包络（0 表示没有口型输入）
};

// 每帧一次。
//   `voiceLevel` = 语音总线当前电平 [0,1]；不上口型的项目一直传 0 也不会错。
//   `dt == 0` 合法（编辑器暂停 / 首帧）：**只算不推进** —— 相位与计时器
//   都不动，但权重仍然按当前状态写一遍（否则暂停时拖一下强度滑条看不到变化）。
ExpressionStats tickExpressions(ecs::World& w, float dt, float voiceLevel);

// 进入运行时 / 读档之后把表情状态对齐：清掉相位、重抽眨眼计时种子，
// 并按当前预设写一次权重（否则第一帧是 T-pose 的中性脸，第二帧才变）。
// `reseed = false` 时保留已有种子（读档不该改变"接下来什么时候眨眼"
// 这件事本身没意义，但保留可以让读档前后的肉眼观感连续）。
void syncExpressionPlayState(ecs::World& w, bool reseed);

// 把某个实体切到指定预设（`name` 为空 = 回到中性，但**不**清手动通道）。
// 返回 false = 这个实体没有 `ExpressionComponent` / 资产没加载 / 名字不存在。
// 单独做成接口而不是让调用方直接改字段：命令与 Inspector 都要一条
// `EXPR-SET` 日志，而"日志必须与执行同源"意味着两边只能走同一条路。
bool setExpressionPreset(ecs::World& w, ecs::Entity e,
                         const std::string& name, std::string* err);

// 数值自检（`Game.exe --selftest expression`）：无窗口、无设备。
int runExpressionSelfTest();

} // namespace anim
