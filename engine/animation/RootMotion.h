#pragma once
// ============================================================
// animation/RootMotion —— 把"位移"从姿势里提出来（B3，2026-10-26）
// ============================================================
//
// 要解决的事：一段走路动画里，角色的前进是**烘在动画数据里**的 ——
// 根骨（髋部）每帧往前挪一点。引擎如果照搬，模型会在原地"越走越远"，
// 最后从角色实体里走出去；而如果不用它，就只能靠代码硬推 Transform，
// 结果一定是"脚在原地划水"（步幅和速度对不上）。
//
// 根运动 = 把根骨这一帧相对上一帧的**增量**取出来，交给实体，同时把
// 增量从姿势里扣掉（in-place），于是：
//   · 实体真的在前进（`TransformComponent` 变了 → 相机/物理/BVH 都跟着）
//   · 模型相对实体停在原地（脚不打滑，因为步幅还是动画给的）
//
// ------------------------------------------------------------
// 为什么是"增量"而不是"绝对位置"
// ------------------------------------------------------------
// 绝对位置只在第一帧有意义（动画第 0 帧的根骨位置）。用增量之后：
//   · 用户拖时间轴 / 跳帧 → 只丢一帧的位移，不会把角色瞬移到别处
//   · 循环片段接回开头那一下 → 增量是个巨大负数，必须**丢弃**（见下）
//   · 叠加混合（过渡期两份姿势）→ 增量天然是"混合后姿势"的一部分
//
// ⚠⚠ **跨圈的那一帧必须丢弃增量**。走路循环从末帧接回首帧时，根骨会
//   从"前方 1.5 m"瞬回"原点" —— 那一帧的增量是 **-1.5 m**。不丢的话
//   角色每走一步就被拉回原地，表现为"原地抽搐"。这一条是这一刀最容易
//   写漏的地方：它只在**循环回绕的那一帧**发生，不写日志根本看不见。
//   判据（自检 `rm_wrap_discard`）：让动画跑满一圈，总位移 ≈ 一圈的
//   前进量，而不是 0。
//
// ------------------------------------------------------------
// ⚠⚠ 坐标系：这是这一刀唯一真正阴的地方
// ------------------------------------------------------------
// `poseToWorld` 输出的世界矩阵**不一定在引擎坐标系里**：
//   · glTF 路径：`joints` 是文件原始空间（Y-up），Y-up→Z-up 藏在
//     `invMeshNode` 里 → 世界矩阵是 **Y-up**
//   · FBX 路径：ufbx 加载时就转成了 Z-up，`invMeshNode` 是单位阵 →
//     世界矩阵**已经是 Z-up**
// 两者平时看不出来（渲染时 `invMeshNode` 与 `push.model` 抵消），但根运动
// 要把位移写进 `TransformComponent`（引擎 Z-up）。所以一律先用
// `Skeleton::skeletonToEngine` 转一道，再谈"水平/垂直"。
// 不转的症状：glTF 角色走路时**朝天上飘**，而且俯视看完全不动。
//
// ------------------------------------------------------------
// 与 B1（动画层）/ B2（动画事件）的关系
// ------------------------------------------------------------
// 根运动只从**底座**取（第 0 层）。附加层即使带了根位移也不提 —— 理由：
// 附加层是"上半身挥手"这类局部动作，它的根位移通常是复制底座动画时
// 一起带过来的垃圾数据；把它算进去会让"挥手时角色往前窜一下"。
// 事件（B2）不受影响：事件按各自层的播放头分发，与位移无关。
// ============================================================

#include "animation/Pose.h"
#include "assets/Skeleton.h"

#include <glm/glm.hpp>

#include <string>

namespace animation {

// 一帧的根运动增量。**全部在引擎世界空间**（Z-up，米/弧度）。
// `valid == false` 时三个量都是 0 —— 调用方不需要再判"要不要用"。
struct RootMotionDelta {
    glm::vec3 position{0.0f};   // 位移增量（引擎世界，Z-up）
    float yaw = 0.0f;           // 朝向增量（绕引擎 +Z，弧度，已 wrap 到 [-π,π]）
    bool valid = false;

    bool isZero() const {
        return position.x == 0.0f && position.y == 0.0f &&
               position.z == 0.0f && yaw == 0.0f;
    }
};

// 找"根运动骨"：`name` 非空就按 `Skeleton::findJoint` 那套匹配
// （不分大小写 / 允许包含 / 跳过末端辅助骨）；空则自动 —— 拓扑序里
// **第一根 `parent == -1`** 的骨。
//
// ⚠ 自动选中的通常是骨盆而不是 armature：armature 节点不在 `joints` 里，
//   所以 Mixamo 的 `mixamorig:Hips` 就是 `parent == -1`。Blender 导出的
//   骨架有时会多一层 `Root`（静止在原点、不带动画），那时自动会选到它
//   —— 它不动 ⇒ 增量恒为 0 ⇒ 表现成"开了根运动但角色不走"。
//   这种情况必须显式填 `rootMotionBone`。引擎会在
//   `ANIM-ROOTMOTION` 锚点里报出**实际用的骨名**，对不上时一眼能看见。
// 返回 -1 = 找不到（该实体整条根运动链关闭，不报错）。
int resolveRootBone(const assets::Skeleton& skel, const std::string& name);

// 某根骨在**骨架空间**的世界矩阵（沿父链累乘，根用 `externalChain`）。
// 只走一条链（深度是个位数），不像 `poseToWorld` 那样算整棵树。
// 表达式与 `Pose::poseToWorld` 逐字段一致（同一份 `composeLocalTRS`）。
glm::mat4 boneWorldInSkeleton(const assets::Skeleton& skel, const Pose& pose,
                              int joint);

// 上一帧世界矩阵 → 这一帧世界矩阵，取出增量。
//
// `horizontalOnly` = true 时**丢掉落差**（引擎 Z 分量置 0）：语义是
// "位移进物理、脚不打滑但不离地" —— 动画里的上下起伏（跑步的弹跳、
// 落地缓冲）留在姿势里当成表演，不写进实体高度。否则角色会随着
// 每次落脚上下颠，物理还会把它当成"一直在跳"。
RootMotionDelta extractRootMotion(const assets::Skeleton& skel,
                                  const glm::mat4& prevWorld,
                                  const glm::mat4& curWorld,
                                  bool horizontalOnly);

// 把根骨钳回基准位置（in-place）—— 只改 `pose.translation[joint]`。
//
// ------------------------------------------------------------
// ⚠⚠ 为什么是"钳到基准"而不是"减去这一帧的增量"
// ------------------------------------------------------------
// 第一版写的是 `pose.translation[root] -= 本帧增量`，看起来天经地义，
// 实际上是**双倍位移**：
//   帧 n 的 pose 是**重新采样**出来的，根已经在"动画当前时刻的位置"
//   （比如 0.98 m）。减掉这一帧的增量（0.016 m）之后停在 0.96 m ——
//   它只是**滞后一帧**，并没有回到原点。而实体那边又累加了 0.98 m，
//   于是画面上角色走了将近 2 米，物理还以为是 0.98。
//   症状：脚步和位移对不上（走一步滑半步），且**每帧日志都是对的**。
// 正确做法是把根钉在**基准点**（第一次提取时那个位置）：每帧都设回同一
// 个值，于是根相对实体恒为 0，实体拿走全部位移。
//
// `baseWorldPos` 由调用方在第一次提取时记录（引擎空间）。不能直接用
// `restLocal` 当基准：动画第 0 帧的根位置常常跟绑定姿势不一样（美术在
// 绑定之后又调过骨盆高度），钉到 rest 会让角色在 Play 的第一帧**跳一下**。
//
// `horizontalOnly` = true 时只钳水平（引擎 XY），保留垂直 —— 即
// "脚不打滑但不离地"：跑跳的上下起伏留在姿势里当表演，不写进实体高度。
//
// 返回被扣掉的偏移（引擎空间，米）。全零 = 已经对齐（没有东西可扣）。
glm::vec3 stripRootMotion(const assets::Skeleton& skel, Pose& pose, int joint,
                          const glm::vec3& curWorldPos,
                          const glm::vec3& baseWorldPos, bool horizontalOnly);

// 某根骨在**引擎空间**的世界位置（`skeletonToEngine` 已乘上）。
glm::vec3 boneWorldPosition(const assets::Skeleton& skel, const Pose& pose,
                            int joint);

// 从四元数里取"绕某个轴的扭转角"（swing-twist 分解）。
//
// 为什么不直接 `atan2(right.y, right.x)`：世界矩阵的 X 轴在某些骨骼上
// 可以指向近乎垂直的方向，atan2 会在那一瞬间跳 ±π —— 表现在画面上是
// "角色走着走着突然转身 180° 又转回来"，而每一帧的 delta 都"看着很小"
// （因为跳变被 wrap 吃掉了）。swing-twist 直接把非扭转分量丢给 swing，
// 扭转分量永远是连续的小角度。
float twistAngleAround(const glm::quat& q, const glm::vec3& axis);

} // namespace animation
