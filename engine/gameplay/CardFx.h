#pragma once
// ============================================================
// gameplay/CardFx —— 卡牌专属表现模板（P3-4）
//
// ------------------------------------------------------------
// 它解决的是什么
// ------------------------------------------------------------
// `P1` 的 `.veffect` 已经能让"一次命中"配成数据，但**卡牌游戏的动作**
// 不是"命中"：出牌、抽牌、加盾、上状态、消耗……每个动作该出什么、飘什么字、
// 落在谁身上，是另一套约定。没有这一层的话，每个项目的作者都要在脚本里
// 为每张牌手写三四行，而且十个项目会写出十种不一致的手感。
//
// 所以这里只有一张**默认表**：`CardFxKind` → `{ .veffect, 飘字种类, 落点 }`。
// 作者要改感觉就改 `.veffect` 本身（粒子/音效/震屏都在里面），
// 不必改代码 —— 这正是"模板"与"硬编码"的区别。
//
// ------------------------------------------------------------
// 三条约定
// ------------------------------------------------------------
// 1) **`effect` 为空 = 不出粒子**。抽牌/弃牌在卡牌游戏里是 UI 动作，
//    往世界里喷火花只会让人以为"场上发生了什么事"。要出粒子就往表里填
//    资产名，不要"顺手给所有动作都挂一个"。
//
// 2) **`PopupKind::Count` = 不弹字**。用 `Count` 当哨兵而不是加一个
//    `bool popup` 字段：两个字段可以互相矛盾（`popup=true` 但 kind 非法），
//    一个字段不会。
//
// 3) **落点只有两种**：目标身上 / 持牌者身上。没有"屏幕中央"——
//    那需要 UI 坐标，而这一层（`gameplay/`）不认识屏幕。
// ============================================================

#include "gameplay/DamageNumbers.h"

namespace gameplay {

// 一次卡牌动作。顺序 = 表的下标，**只能追加**。
enum class CardFxKind : int {
    Play = 0,     // 牌打出去（在持牌者身上）
    Hit = 1,      // 造成伤害（在目标身上）
    Crit = 2,     // 暴击（同 Hit，但飘字换成 Crit 样式）
    Heal = 3,     // 治疗
    Shield = 4,   // 加护盾
    Buff = 5,     // 上状态 / 加能量
    Draw = 6,     // 抽牌（默认不出粒子、不弹字）
    Discard = 7,  // 进弃牌堆
    Exhaust = 8,  // 进消耗区
    Count = 9,
};

struct CardFxPreset {
    // 相对资产根的路径（`fx/xxx.veffect`）。空 = 不出粒子。
    const char* effect = "";
    // 飘字种类。`PopupKind::Count` = 不弹字。
    PopupKind popup = PopupKind::Count;
    // true = 落在目标身上；false = 落在持牌者身上。
    bool atTarget = true;
    // 飘字离地高度（米）。世界是米制、Z-up，角色身高约 1.8。
    float height = 1.7f;
};

// 越界 → 返回 Play 那一行（不抛、不留空：一处枚举笔误不该让整场战斗
// 一个表现都没有，而是"表现退化成出牌"）。
const CardFxPreset& cardFxPreset(CardFxKind k);

} // namespace gameplay
