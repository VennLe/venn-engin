// engine/ui/ThemeSelfTest —— 主题系统的自检（`Game.exe --selftest theme`）
//
// 为什么主题也要有自检：
//   主题是**纯数据 + 一次应用**，看起来"看一眼截图就知道对不对"。但它有两
//   类 bug 是截图看不出来的：
//     ① **落盘下标错位** —— 往 ThemeId 中间插一套新主题，老配置里写入的
//        `theme=2` 会静默变成另一套风格。用户只会觉得"我的设置自己变了"。
//     ② **派生主题塌成同一个颜色** —— 新加的一套主题忘了给 accent，全部
//        走默认分支，于是 10 套里有 3 套看起来一模一样（而下拉里名字不同）。
//   这两类都能用纯数值断言钉死，不需要 GPU。
//
// 与本轮（2026-10-27 二次元改造）对应的不变量：
//   A 下标稳定：0~4 的**关键色**逐字段等于改造前的值
//   B 每套都不同：10 套两两的 (windowBg, accent) 不重复
//   C 明暗自洽：isLight 与 windowBg 亮度方向一致；动漫深色档确实更暗
//   D 度量：动漫档圆角 >= 10 且无硬边框；工程档圆角 >= 8
//   E 应用：applyTheme 越界被夹、幂等；tokens()/metrics() 跟着变
// ============================================================

