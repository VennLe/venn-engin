#pragma once
// ============================================================
// ui2/UiAction —— 界面动作的**语法与解析**（2026-11-02）
//
// ------------------------------------------------------------
// 它补的是什么洞
// ------------------------------------------------------------
// 在它之前，`.ui.json` 里的控件**只能看、不能碰**：`drawDocument` 把按钮
// 画出来，但没有任何命中测试，也没有"点了做什么"这个概念（
// `grep -rn action engine/ui2/` → 0）。于是 U2/U6 那套 `UiButton` +
// `UiFocus`（暂停菜单用的）是**另一条路**，文档层完全没接上 ——
// 作者摆出来的按钮是纯装饰。
//
// ------------------------------------------------------------
// 为什么是"字符串动作"而不是回调注册
// ------------------------------------------------------------
// ① UI 文档是**资产**，要能存盘、要被策划改。函数指针存不进 JSON，
//    而"注册一张 id → std::function 的表"意味着界面上每个按钮都要
//    在 C++ 里再写一次 —— 那正是这份文档要消灭的东西。
// ② 引擎不该认识玩法。`flag:` / `toggle:` 这两种动词已经能表达
//    "记住玩家选了啥"（脚本每帧轮询这个旗标），剩下的逻辑在脚本里。
// ③ 解析放在引擎、**执行**放在宿主（`runtime`）：旗标表住在 runtime，
//    engine 不能反过来依赖它（分层是 runtime → engine）。所以本文件
//    **只解析，不执行**。
//
// ------------------------------------------------------------
// 动词表（就四个，别加第五个除非真的表达不了）
// ------------------------------------------------------------
//   flag:<key>=<number>   写旗标。省略 `=number` 等价于 `=1`
//   toggle:<key>          旗标 0↔1 取反（"再点一下关掉"）
//   sound:<clip>          播一声（走宿主音频，一次性音效）
//   quit                  退出游戏
//
// ------------------------------------------------------------
// 为什么**没有** `emit:`（2026-11-02 当场砍掉的）
// ------------------------------------------------------------
// 原本想加一个"把事件交给脚本"的动词，落到 `GameServices::uiAction`。
// 写之前查了时序：那一格由 `tickUi` 每帧 `clear()`，而文档层派发发生在
// **渲染阶段**（after onUpdate）—— 于是 emit 写进去的值，下一帧在状态栈
// 读到之前就被清掉了。要救它能救（加一个中转变量），但那是给一个本就不
// 需要的动词加一层状态。
//
// 真正的理由更简单：**这一层的脚本是"每帧轮询"模型**（见
// `AudioSystem::voicePlaying()` 头注释里的同一条推理 —— 不用回调，
// 因为回调会把"UI 点击"变成"主线程重入剧本推进"）。脚本要"知道玩家
// 按了开始"，直接 `flag:menuStart=1` 然后轮询这个旗标就行，语义一样，
// 而且旗标还能进存档。
//
// ⚠ 语义细节
//   · 空串 = **没配动作**，不是错误（装饰性控件合法）。
//   · 动词与 key **都区分大小写**，而且不许含空格 —— 日志按 `\S*` 解析。
//   · 解析失败**不阻断文档加载**：一条 action 写错不该让整份界面加载
//     失败（那会把"某个按钮点不动"升级成"进游戏一片空白"）。所以
//     解析器返回 false + 原因，`parseUiDocument` 把它塞进 `warnings`，
//     运行时按"点不动 + 一条 WARN"处理。
// ============================================================

#include <string>

namespace ui2 {

enum class UiActionKind : int {
    None = 0,
    Flag,     // flag:<key>=<number>
    Toggle,   // toggle:<key>
    Sound,    // sound:<clip>
    Quit,     // quit
    Count = 4,
};

// 日志/存档里用的名字（**不翻译**：它是标识符）。
const char* uiActionKindName(UiActionKind k);
bool uiActionKindFromName(const std::string& s, UiActionKind& out);

struct UiAction {
    UiActionKind kind = UiActionKind::None;
    std::string key;      // 旗标名 / 事件名 / clip 路径（Quit 时为空）
    double value = 1.0;   // Flag 的值（其它动词不用）
};

// 解析一段动作文本。
//   空串        → true，`out.kind == None`
//   认得        → true，填好 out
//   认不得      → false，`err` 写清"哪个动词不认识 / 缺什么"，`out` 置 None
bool parseUiAction(const std::string& text, UiAction& out, std::string* err);

// 一行回显（日志用，不翻译）。None 时返回 `(none)`。
std::string uiActionDescribe(const UiAction& a);

}  // namespace ui2
