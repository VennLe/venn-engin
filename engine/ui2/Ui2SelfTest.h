// ============================================================
// ui2/Ui2SelfTest —— 游戏 UI 的无窗口数值自检（U0 起）
//
// 为什么要有：UI 的绝大部分断言（颜色 / 上屏 / 交互）必须开窗口 + 有 GPU，
// 但"布局比例算对没算对 / 文本宽度量对没量对 / 焦点导航跳对没跳对"全是
// **纯 CPU 数值**。把它们单独剥出来，回归里就有一项**毫秒级**的用例，
// 而不是每改一行都要等 40 秒的 GUI 启动。
//
// 这是角色链 A0-5（`MYVK_ANIM_TEST`）的同一套做法：
//   · 入口在 `main()` 里，**在 Vulkan / 窗口之前** return；
//   · 每项打一行 `UI2-TEST <name> actual=.. expected=.. tol=.. result=..`；
//   · 结尾一行 `UI2-TOTAL pass=%d fail=%d`；
//   · ⚠ `detail=` 之类的附加字段里**不能有空格**（脚本按 `\S*` 解析）。
// ============================================================

