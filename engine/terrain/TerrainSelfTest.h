//   · 高度场的法线符号反了 → 30° 坡变成"反 30°"，角色照样站着
// 这些都不能靠截屏发现。所以全部用**解析解**当基准断言。
//
// 运行方式：`Game.exe --selftest terrain`（不开窗口、不需要 GPU）。
// 输出：`TERRAIN-T pass <名字> <细节>` / `TERRAIN-TOTAL pass= fail=`。
// ============================================================

